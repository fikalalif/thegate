"""Provider-agnostic domain schemas for chat requests, responses, and model candidates."""

import uuid
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator


class ChatMessage(BaseModel):
    """Unified chat message representation across all providers."""

    role: str = Field(description="Role of the message author (system, user, assistant, tool)")
    content: str | list[dict[str, Any]] | None = Field(
        default=None, description="Message text or multimodal content blocks"
    )
    name: str | None = Field(default=None, description="Optional author name")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="Tool calls generated by the model"
    )
    tool_call_id: str | None = Field(
        default=None, description="Tool call reference ID when role is tool"
    )


class ChatChoice(BaseModel):
    """Individual completion choice within a chat completion response."""

    index: int = Field(default=0, description="Choice index")
    message: ChatMessage = Field(description="Chat message returned by the model")
    finish_reason: str | None = Field(
        default="stop", description="Reason model stopped generating (stop, length, tool_calls)"
    )


class TokenUsage(BaseModel):
    """Token usage counters reported or estimated for a request."""

    prompt_tokens: int = Field(default=0, ge=0, description="Tokens in the prompt")
    completion_tokens: int = Field(
        default=0, ge=0, description="Tokens in the generated completion"
    )
    total_tokens: int = Field(default=0, ge=0, description="Total tokens consumed")


class StreamDelta(BaseModel):
    """Delta payload representing an incremental chunk in an SSE stream."""

    role: str | None = Field(default=None, description="Role update if changed")
    content: str | None = Field(default=None, description="Incremental text fragment")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="Incremental tool call fragments"
    )


class StreamChoice(BaseModel):
    """Individual choice container within a stream chunk."""

    index: int = Field(default=0, description="Choice index")
    delta: StreamDelta = Field(description="Incremental delta content")
    finish_reason: str | None = Field(
        default=None, description="Finish reason if generation finished on this chunk"
    )


class StreamChunk(BaseModel):
    """Unified stream chunk emitted over Server-Sent Events (SSE)."""

    id: str = Field(description="Unique stream chunk identifier")
    model: str = Field(description="Model identifier producing the stream")
    choices: list[StreamChoice] = Field(
        default_factory=list, description="List of incremental choices"
    )
    usage: TokenUsage | None = Field(
        default=None, description="Optional token usage included in terminal chunk"
    )
    created: int | None = Field(default=None, description="Epoch timestamp in seconds")

    @model_validator(mode="before")
    @classmethod
    def normalize_delta_and_finish_reason(cls, data: Any) -> Any:
        """Allow direct initialization with delta and finish_reason for convenience."""
        if isinstance(data, dict):
            if "delta" in data and "choices" not in data:
                delta = data.pop("delta")
                finish_reason = data.pop("finish_reason", None)
                index = data.pop("index", 0)
                if isinstance(delta, dict):
                    stream_delta = StreamDelta(**delta)
                elif isinstance(delta, StreamDelta):
                    stream_delta = delta
                else:
                    stream_delta = StreamDelta(content=str(delta))
                data["choices"] = [
                    StreamChoice(index=index, delta=stream_delta, finish_reason=finish_reason)
                ]
        return data

    @property
    def delta(self) -> StreamDelta | None:
        """Convenience property to access primary choice delta."""
        if self.choices:
            return self.choices[0].delta
        return None

    @property
    def finish_reason(self) -> str | None:
        """Convenience property to access primary choice finish reason."""
        if self.choices:
            return self.choices[0].finish_reason
        return None


class UnifiedChatRequest(BaseModel):
    """Provider-agnostic chat completion request payload."""

    model: str = Field(min_length=1, description="Target model internal name or backend ID")
    messages: list[ChatMessage] = Field(
        min_length=1, description="Ordered list of conversation messages"
    )
    temperature: float | None = Field(
        default=None, ge=0.0, le=2.0, description="Sampling temperature"
    )
    max_tokens: int | None = Field(
        default=None, gt=0, description="Maximum tokens to generate"
    )
    stream: bool = Field(default=False, description="Whether to stream response chunks via SSE")
    tools: list[dict[str, Any]] | None = Field(
        default=None, description="List of available tools/functions"
    )
    tool_choice: Any | None = Field(default=None, description="Controls which tool is called")
    response_format: dict[str, Any] | None = Field(
        default=None, description="Structured output configuration (e.g. json_object)"
    )
    top_p: float | None = Field(
        default=None, ge=0.0, le=1.0, description="Nucleus sampling probability"
    )
    frequency_penalty: float | None = Field(
        default=None, ge=-2.0, le=2.0, description="Frequency penalty"
    )
    presence_penalty: float | None = Field(
        default=None, ge=-2.0, le=2.0, description="Presence penalty"
    )
    stop: list[str] | str | None = Field(
        default=None, description="Stop sequence(s) to halt generation"
    )
    extra_params: dict[str, Any] = Field(
        default_factory=dict, description="Additional provider-specific parameters"
    )


class UnifiedChatResponse(BaseModel):
    """Provider-agnostic chat completion response payload."""

    id: str = Field(description="Unique completion identifier")
    model: str = Field(description="Internal or backend model identifier")
    choices: list[ChatChoice] = Field(
        min_length=1, description="List of generated completion choices"
    )
    usage: TokenUsage | None = Field(default=None, description="Token usage statistics")
    created: int | None = Field(default=None, description="Epoch timestamp of generation")
    system_fingerprint: str | None = Field(
        default=None, description="Upstream backend system fingerprint"
    )


class ModelCandidate(BaseModel):
    """Model candidate metadata used by routing policies and adapters."""

    id: uuid.UUID | str = Field(description="Unique model registry identifier")
    internal_name: str = Field(
        min_length=1, description="Human-readable internal model identifier"
    )
    backend_model_id: str = Field(
        min_length=1, description="Downstream provider backend model identifier"
    )
    provider_adapter: str = Field(
        default="9router", description="Adapter handler identifier"
    )
    capabilities: dict[str, Any] = Field(
        default_factory=dict, description="Model capabilities (tools, json_mode, vision, etc.)"
    )
    context_limit: int | None = Field(
        default=None, gt=0, description="Maximum context window in tokens"
    )
    enabled: bool = Field(default=True, description="Whether the model is active and eligible")

    model_config = ConfigDict(from_attributes=True)
