"""OpenAI-compatible request and response schemas for chat completions."""

import time
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class ChatCompletionMessageParam(BaseModel):
    """Message object in an OpenAI chat completion request."""

    role: str = Field(description="The role of the author of this message.")
    content: str | list[dict[str, Any]] | None = Field(
        default=None, description="The contents of the message."
    )
    name: str | None = Field(default=None, description="An optional name for the participant.")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="The tool calls generated by the model."
    )
    tool_call_id: str | None = Field(
        default=None, description="Tool call that this message is responding to."
    )

    model_config = ConfigDict(extra="allow")


class ChatCompletionRequest(BaseModel):
    """OpenAI-compliant chat completion request specification."""

    model: str = Field(min_length=1, description="ID of the model to use.")
    messages: list[ChatCompletionMessageParam] = Field(
        min_length=1, description="A list of messages comprising the conversation so far."
    )
    temperature: float | None = Field(
        default=None, ge=0.0, le=2.0, description="Sampling temperature between 0 and 2."
    )
    top_p: float | None = Field(
        default=None, ge=0.0, le=1.0, description="Nucleus sampling probability mass."
    )
    max_tokens: int | None = Field(
        default=None, gt=0, description="The maximum number of tokens to generate."
    )
    stream: bool = Field(default=False, description="If set, partial message deltas will be sent.")
    stream_options: dict[str, Any] | None = Field(
        default=None, description="Options for streaming response (e.g. include_usage)."
    )
    tools: list[dict[str, Any]] | None = Field(
        default=None, description="A list of tools the model may call."
    )
    tool_choice: Any | None = Field(
        default=None, description="Controls which (if any) tool is called by the model."
    )
    response_format: dict[str, Any] | None = Field(
        default=None, description="An object specifying the format that the model must output."
    )
    presence_penalty: float | None = Field(
        default=None, ge=-2.0, le=2.0, description="Penalty for new topics."
    )
    frequency_penalty: float | None = Field(
        default=None, ge=-2.0, le=2.0, description="Penalty for verbatim repetition."
    )
    stop: list[str] | str | None = Field(
        default=None, description="Up to 4 sequences where the API will stop generating."
    )
    user: str | None = Field(
        default=None, description="A unique identifier representing your end-user."
    )

    model_config = ConfigDict(extra="allow")


class ChatCompletionResponseMessage(BaseModel):
    """The message generated by the model in non-streaming responses."""

    role: str = Field(default="assistant", description="The role of the author of this message.")
    content: str | None = Field(default=None, description="The contents of the message.")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="The tool calls generated by the model."
    )


class ChatCompletionChoice(BaseModel):
    """Individual choice container within ChatCompletionResponse."""

    index: int = Field(default=0, description="The index of the choice in the list of choices.")
    message: ChatCompletionResponseMessage = Field(
        description="A chat completion message generated by the model."
    )
    finish_reason: str | None = Field(
        default="stop", description="The reason the model stopped generating tokens."
    )


class CompletionUsage(BaseModel):
    """Token usage counters for the chat completion."""

    prompt_tokens: int = Field(default=0, ge=0, description="Number of tokens in the prompt.")
    completion_tokens: int = Field(
        default=0, ge=0, description="Number of tokens in the generated completion."
    )
    total_tokens: int = Field(
        default=0, ge=0, description="Total number of tokens used in the request."
    )


class ChatCompletionResponse(BaseModel):
    """OpenAI-compliant chat completion response representation."""

    id: str = Field(description="A unique identifier for the chat completion.")
    object: str = Field(default="chat.completion", description="The object type.")
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="The Unix timestamp of when the completion was created.",
    )
    model: str = Field(description="The model used for the chat completion.")
    choices: list[ChatCompletionChoice] = Field(
        description="A list of chat completion choices."
    )
    usage: CompletionUsage | None = Field(
        default=None, description="Usage statistics for the completion request."
    )
    system_fingerprint: str | None = Field(
        default=None, description="Backend configuration fingerprint."
    )


class ChatCompletionChunkDelta(BaseModel):
    """Delta payload emitted inside an SSE chunk choice."""

    role: str | None = Field(default=None, description="The role of the author of this message.")
    content: str | None = Field(default=None, description="The contents of the chunk message.")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="The tool calls generated by the model."
    )


class ChatCompletionChunkChoice(BaseModel):
    """Choice container within ChatCompletionChunk."""

    index: int = Field(default=0, description="Choice index.")
    delta: ChatCompletionChunkDelta = Field(description="Incremental delta generated.")
    finish_reason: str | None = Field(
        default=None, description="The reason the model stopped generating tokens."
    )


class ChatCompletionChunk(BaseModel):
    """OpenAI-compliant chunk emitted over Server-Sent Events."""

    id: str = Field(description="A unique identifier for the chunk.")
    object: str = Field(default="chat.completion.chunk", description="The object type.")
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="The Unix timestamp of when the chunk was created.",
    )
    model: str = Field(description="The model used for the completion.")
    choices: list[ChatCompletionChunkChoice] = Field(
        default_factory=list, description="A list of chunk choices."
    )
    usage: CompletionUsage | None = Field(
        default=None, description="Token usage statistics (if included in terminal chunk)."
    )
    system_fingerprint: str | None = Field(
        default=None, description="Backend configuration fingerprint."
    )


class OpenAIErrorDetail(BaseModel):
    """OpenAI error object specification."""

    message: str = Field(description="Human-readable error message.")
    type: str = Field(default="invalid_request_error", description="Error category.")
    param: str | None = Field(default=None, description="Parameter causing the error.")
    code: str | None = Field(default=None, description="Specific error code.")


class OpenAIErrorResponse(BaseModel):
    """OpenAI error response container."""

    error: OpenAIErrorDetail = Field(description="Error details.")
